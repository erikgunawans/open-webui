/**
 * Generate the Notulen Rapat Direksi data modules from the design handoff, so the 150-property
 * schema, the guide text and the demo meeting are never hand-typed.
 *
 *   design_handoff_notulen_rapat_direksi/notulen-data.js     → src/lib/notulen/schema.ts
 *   design_handoff_notulen_rapat_direksi/rapat-dummy-data.js → src/lib/notulen/demo-source.ts
 *
 * Usage: bun scripts/gen-schema.ts   (then the repo's prettier formats the output)
 *
 * Both sources assign a global (`window.NOTULEN_DATA`, `window.RAPAT`); they are evaluated with a
 * stand-in `window` and nothing else, and the result is checked before anything is written.
 */
import { join } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const SRC = join(ROOT, 'design_handoff_notulen_rapat_direksi');
const OUT = join(ROOT, 'src', 'lib', 'notulen');

const TYPES = [
	'title',
	'rich_text',
	'people',
	'files',
	'checkbox',
	'select',
	'status',
	'multi_select',
	'date',
	'number',
	'url'
];

type Field = { name: string; type: string; options: string[]; description: string | null };

const load = async (file: string, key: string): Promise<any> => {
	const code = await Bun.file(join(SRC, file)).text();
	const window: Record<string, unknown> = {};
	new Function('window', code)(window);
	if (!window[key]) throw new Error(`${file} did not define window.${key}`);
	return window[key];
};

const data = await load('notulen-data.js', 'NOTULEN_DATA');
const schema: { name: string; fields: Field[] }[] = data.schema;

if (schema.length !== 9) throw new Error(`expected 9 databases, found ${schema.length}`);
const total = schema.reduce((n, db) => n + db.fields.length, 0);
if (total !== 150) throw new Error(`expected 150 properties, found ${total}`);
for (const db of schema) {
	const names = new Set<string>();
	for (const f of db.fields) {
		if (!TYPES.includes(f.type)) throw new Error(`${db.name}.${f.name}: unknown type ${f.type}`);
		if (names.has(f.name)) throw new Error(`${db.name}: duplicate property ${f.name}`);
		names.add(f.name);
	}
	if (db.fields.filter((f) => f.type === 'title').length !== 1)
		throw new Error(`${db.name}: needs exactly one title property`);
}

const header = (source: string) =>
	`// GENERATED by scripts/gen-schema.ts from design_handoff_notulen_rapat_direksi/${source}.\n` +
	`// Do not edit by hand: change the source and run \`bun scripts/gen-schema.ts\`.\n\n`;

const json = (v: unknown) => JSON.stringify(v, null, '\t');

const schemaTs =
	header('notulen-data.js') +
	`/** The nine databases: index 0 = Informasi & Ringkasan Rapat, 1..8 = agendas. */\n` +
	`export const SCHEMA = ${json(
		schema.map((db) => ({
			name: db.name,
			fields: db.fields.map((f) => ({
				name: f.name,
				type: f.type,
				options: f.options ?? [],
				description: f.description ?? null
			}))
		}))
	)} as const;\n\n` +
	`/** The original template guide, as HTML. Rendered as-is in Panduan. */\n` +
	`export const GUIDE_HTML = ${json(data.guide)};\n\n` +
	`export const FOOTER = ${json(data.footer)};\n\n` +
	`export const NOTE = ${json(data.note)};\n\n` +
	`/** The body of the second Informasi record in the initial template. */\n` +
	`export const INFO2_BODY = ${json(data.info2body)};\n`;

const rapat = await load('rapat-dummy-data.js', 'RAPAT');
const demoTs =
	header('rapat-dummy-data.js') +
	`// Fictional names and figures for /ruang-pimpinan/rapat/demo. Not JUP data.\n` +
	`export const RAPAT_DEMO = ${json(rapat)} as const;\n`;

await Bun.write(join(OUT, 'schema.ts'), schemaTs);
await Bun.write(join(OUT, 'demo-source.ts'), demoTs);
console.log(`wrote schema.ts (${schema.length} databases, ${total} properties) and demo-source.ts`);
