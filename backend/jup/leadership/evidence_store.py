"""Where evidence files live: the host's storage provider, under `leadership/evidence/` (ADR-0014).

Not the vendor's `open_webui.storage.provider`. Its GCS `get_file` and `delete_file` keep only the
first path segment of a key, so a nested `leadership/evidence/...` key would break. It also writes
a copy of every upload into the vendor's own `UPLOAD_DIR`, and evidence must never be reachable
through the vendor Files paths (ADR-0014, HOST-04). This module follows the same
`STORAGE_PROVIDER` / `GCS_BUCKET_NAME` configuration, so production writes to the `jup-ops-data`
bucket, and it touches nothing outside its own prefix.

Keys are generated by the server from the content hash: `leadership/evidence/<sha256>`. The
client's filename is metadata on the evidence row and never part of a path, so it cannot
traverse or collide. Identical bytes share one object, which also makes a retried upload
harmless.

Checks happen before anything is stored:
- a size cap (`JUP_LEADERSHIP_EVIDENCE_MAX_BYTES`, default 20 MiB), read with a bound so an
  oversized upload is never held whole in memory;
- a content-type allowlist judged from the bytes themselves. The client's declared type must
  agree with what the bytes are, or the file is refused.
"""

from __future__ import annotations

import hashlib
import os
import zipfile
from dataclasses import dataclass
from io import BytesIO
from pathlib import Path
from typing import BinaryIO, Protocol

PREFIX = 'leadership/evidence/'
DEFAULT_MAX_BYTES = 20 * 1024 * 1024

PDF = 'application/pdf'
PNG = 'image/png'
JPEG = 'image/jpeg'
XLSX = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
DOCX = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
PPTX = 'application/vnd.openxmlformats-officedocument.presentationml.presentation'
CSV = 'text/csv'
TEXT = 'text/plain'
ALLOWED_TYPES = frozenset({PDF, PNG, JPEG, XLSX, DOCX, PPTX, CSV, TEXT})

# The part inside an Office Open XML package that says which kind it is.
_OOXML_MARKERS = {'xl/workbook.xml': XLSX, 'word/document.xml': DOCX, 'ppt/presentation.xml': PPTX}


class EvidenceRejected(ValueError):
    """The file cannot be accepted as evidence. `status` is the HTTP answer: 413, 415 or 422."""

    def __init__(self, status: int, message: str) -> None:
        super().__init__(message)
        self.status = status


@dataclass(frozen=True)
class CheckedFile:
    content: bytes
    sha256: str
    content_type: str
    size: int
    filename: str

    @property
    def key(self) -> str:
        return PREFIX + self.sha256


def max_bytes() -> int:
    value = os.environ.get('JUP_LEADERSHIP_EVIDENCE_MAX_BYTES', '').strip()
    return int(value) if value.isdigit() and int(value) > 0 else DEFAULT_MAX_BYTES


def read_bounded(stream: BinaryIO, limit: int) -> bytes:
    """Read at most `limit` bytes; one byte more means the upload is too large."""
    content = stream.read(limit + 1)
    if len(content) > limit:
        raise EvidenceRejected(413, f'evidence files are limited to {limit} bytes')
    return content


def check_file(content: bytes, filename: str, declared_type: str | None) -> CheckedFile:
    """Accept a file only if its bytes are an allowed type that agrees with the declared one."""
    if not content:
        raise EvidenceRejected(422, 'the evidence file is empty')
    actual = sniff(content)
    if actual is None:
        raise EvidenceRejected(415, 'this file type is not accepted as evidence')
    declared = (declared_type or '').split(';')[0].strip().lower()
    # A browser often declares a CSV as plain text, and plain text is what a CSV sniffs as.
    if declared and declared != actual and {declared, actual} != {CSV, TEXT}:
        raise EvidenceRejected(415, f'the file was declared as {declared} but its content is {actual}')
    if declared == CSV:
        actual = CSV
    name = os.path.basename((filename or '').replace('\\', '/')).strip() or 'evidence'
    return CheckedFile(content, hashlib.sha256(content).hexdigest(), actual, len(content), name[:255])


def sniff(content: bytes) -> str | None:
    """The allowed type these bytes are, or None."""
    if content.startswith(b'%PDF-'):
        return PDF
    if content.startswith(b'\x89PNG\r\n\x1a\n'):
        return PNG
    if content.startswith(b'\xff\xd8\xff'):
        return JPEG
    if content.startswith(b'PK\x03\x04'):
        try:
            with zipfile.ZipFile(BytesIO(content)) as package:
                names = set(package.namelist())
        except zipfile.BadZipFile:
            return None
        for marker, kind in _OOXML_MARKERS.items():
            if marker in names:
                return kind
        return None
    try:
        text = content.decode('utf-8')
    except UnicodeDecodeError:
        return None
    # Text, but not text carrying control bytes a viewer might interpret.
    if any(ord(char) < 32 and char not in '\t\n\r' for char in text):
        return None
    return TEXT


class EvidenceStore(Protocol):
    def put(self, key: str, content: bytes, content_type: str) -> None: ...

    def get(self, key: str) -> bytes: ...


class LocalEvidenceStore:
    """Files under a root directory; for development and tests."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        _check_key(key)
        return self.root / key

    def put(self, key: str, content: bytes, content_type: str) -> None:
        path = self._path(key)
        if path.exists():
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        partial = path.with_suffix('.partial')
        partial.write_bytes(content)
        partial.replace(path)

    def get(self, key: str) -> bytes:
        return self._path(key).read_bytes()


class GCSEvidenceStore:
    """Objects in the host's GCS bucket, under the evidence prefix only."""

    def __init__(self, bucket_name: str) -> None:
        from google.cloud import storage

        self.bucket = storage.Client().bucket(bucket_name)

    def put(self, key: str, content: bytes, content_type: str) -> None:
        _check_key(key)
        blob = self.bucket.blob(key)
        if blob.exists():
            return
        blob.upload_from_string(content, content_type=content_type)

    def get(self, key: str) -> bytes:
        _check_key(key)
        return self.bucket.blob(key).download_as_bytes()


def configured_store() -> EvidenceStore | None:
    """The store the host's storage configuration names, or None when evidence cannot be stored."""
    provider = os.environ.get('STORAGE_PROVIDER', 'local').strip().lower() or 'local'
    if provider == 'gcs':
        bucket = os.environ.get('GCS_BUCKET_NAME', '').strip()
        return GCSEvidenceStore(bucket) if bucket else None
    if provider == 'local':
        data_dir = os.environ.get('DATA_DIR', '').strip()
        return LocalEvidenceStore(Path(data_dir)) if data_dir else None
    # S3 and Azure are not configured anywhere JUP runs; refuse rather than guess.
    return None


def _check_key(key: str) -> None:
    digest = key.removeprefix(PREFIX)
    if not key.startswith(PREFIX) or len(digest) != 64 or any(c not in '0123456789abcdef' for c in digest):
        raise ValueError(f'{key!r} is not an evidence key')
